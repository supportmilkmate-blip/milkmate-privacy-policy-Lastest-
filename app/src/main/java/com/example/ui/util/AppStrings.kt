    // Precomputed phrase replacement lists sorted by length descending for instantaneous rendering
    private val precomputedPhraseReplacements: Map<String, List<Pair<Regex, String>>> by lazy {
        commonPhrases.mapValues { (_, phraseMap) ->
            phraseMap.entries
                .map { (k, v) ->
                    val phrase = k.replace("_", " ")
                    phrase to v
                }
                .filter { it.first.length >= 3 && !it.first.all { c -> c.isDigit() } }
                .sortedByDescending { it.first.length }
                .map { (phrase, trans) ->
                    Regex("(?i)\\b" + Regex.escape(phrase) + "\\b") to trans
                }
        }
    }

    // Precomputed word replacement lists sorted by length descending
    private val precomputedWordReplacements: Map<String, List<Pair<Regex, String>>> by lazy {
        wordTranslations.mapValues { (_, wordMap) ->
            wordMap.entries
                .sortedByDescending { it.key.length }
                .map { (word, trans) ->
                    Regex("(?i)\\b" + Regex.escape(word) + "\\b") to trans
                }
        }
    }

    /**
     * Translates a given key, label, title, or sentence into the user's selected language.
     * Accurately supports multi-word phrases, compound strings, status tokens, and symbols.
     */
    fun get(keyOrPhrase: String, langCode: String = "en"): String {
        if (keyOrPhrase.isBlank()) return keyOrPhrase
        val activeLang = when (langCode) {
            "hr" -> "hi"
            "as" -> "bn"
            else -> langCode
        }
        if (activeLang == "en") return keyOrPhrase

        val langMap = commonPhrases[activeLang] ?: commonPhrases["hi"] ?: return keyOrPhrase

        // 1. Direct exact key or phrase match
        langMap[keyOrPhrase]?.let { return it }

        val trimmed = keyOrPhrase.trim()

        // Extract surrounding parenthetical numbers/amounts like "(12)" or "(₹450)" or "(06:00 AM)"
        val countRegex = Regex("""\s*(\([^\)]+\))\s*$""")
        val countMatch = countRegex.find(trimmed)
        val suffixParenthesis = countMatch?.value ?: ""
        val textWithoutSuffix = if (countMatch != null) trimmed.substring(0, countMatch.range.first).trim() else trimmed

        // Extract leading/trailing symbols, arrows, or emojis
        val leadingSymbolRegex = Regex("""^[🌅🌆🥛👥📊🐄🐃🏢⚙️🌾⛽👷🔧🧀🍬🏺🧪🧈💵📥📤🔄🌐➕+•⇄→🔎📱✓\s\-\:]+""")
        val trailingSymbolRegex = Regex("""[🌅🌆🥛👥📊🐄🐃🏢⚙️🌾⛽👷🔧🧀🍬🏺🧪🧈💵📥📤🔄🌐➕+•⇄→🔎📱✓\s\-\:]+$""")

        val leadingSymbols = leadingSymbolRegex.find(textWithoutSuffix)?.value ?: ""
        val trailingSymbols = trailingSymbolRegex.find(textWithoutSuffix.removePrefix(leadingSymbols))?.value ?: ""

        val cleanCore = textWithoutSuffix
            .removePrefix(leadingSymbols)
            .removeSuffix(trailingSymbols)
            .trim()

        if (cleanCore.isEmpty()) return keyOrPhrase

        // 2. Direct exact match on clean core
        langMap[cleanCore]?.let { return leadingSymbols + it + trailingSymbols + suffixParenthesis }

        // 3. Normalized key match (e.g. "Morning Shift" -> "morning_shift")
        val normalized = cleanCore.lowercase()
            .replace("'", "")
            .replace("’", "")
            .replace("&", "and")
            .replace("•", "")
            .replace("(", "")
            .replace(")", "")
            .replace("/", "_")
            .replace(" ", "_")
            .replace("-", "_")

        langMap[normalized]?.let { return leadingSymbols + it + trailingSymbols + suffixParenthesis }

        for ((k, v) in langMap) {
            val kNormalized = k.lowercase()
            if (kNormalized == normalized || k.replace("_", " ").equals(cleanCore, ignoreCase = true)) {
                return leadingSymbols + v + trailingSymbols + suffixParenthesis
            }
        }

        // 4. Precomputed multi-word phrase replacement
        var localizedCore = cleanCore
        precomputedPhraseReplacements[activeLang]?.forEach { (regex, replacement) ->
            if (regex.containsMatchIn(localizedCore)) {
                localizedCore = regex.replace(localizedCore, replacement)
            }
        }

        // 5. Precomputed single-word token replacement
        precomputedWordReplacements[activeLang]?.forEach { (regex, replacement) ->
            if (regex.containsMatchIn(localizedCore)) {
                localizedCore = regex.replace(localizedCore, replacement)
            }
        }

        return leadingSymbols + localizedCore + trailingSymbols + suffixParenthesis
    }
}

@Composable
@ReadOnlyComposable
fun appStr(keyOrPhrase: String): String {
    val lang = LocalAppLanguage.current
    return AppStrings.get(keyOrPhrase, lang)
}

@Composable
@ReadOnlyComposable
fun String.loc(): String {
    val lang = LocalAppLanguage.current
    return AppStrings.get(this, lang)
}
